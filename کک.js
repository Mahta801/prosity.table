const table = document.getElementById("periodic-table");
const info = document.getElementById("element-info");
const search = document.getElementById("search");

function showInfo(element) {
    info.innerHTML = `
        <h2>${element.name} (${element.symbol})</h2>

        <p>عدد اتمی: ${element.number}</p>
        <p>جرم اتمی: ${element.mass}</p>
        <p>نوع عنصر: ${element.type}</p>
        <p>خانواده شیمیایی: ${element.family}</p>
        <p>حالت در دمای اتاق: ${element.state}</p>
        <p>گروه: ${element.family === "لانتانید" || element.family === "اکتینید" ? "از سری عناصر داخلی" : element.group}</p>
        <p>دوره: ${element.period <= 7 ? element.period : element.period === 8 ? 6 : 7}</p>
    `;
}

function showElements(list) {
    table.innerHTML = "";

    if (list.length === 0) {
        table.innerHTML = `
            <p class="empty-message">عنصری پیدا نشد!</p>
        `;
        return;
    }

    list.forEach(element => {
        const card = document.createElement("div");

        card.className = "element";
        card.style.gridColumn = element.group;
        card.style.gridRow = element.period;
        card.style.backgroundColor = colors[element.family];

        card.innerHTML = `
            <span class="number">${element.number}</span>
            <span class="symbol">${element.symbol}</span>
            <span class="name">${element.name}</span>
        `;

        card.addEventListener("click", () => {
            document.querySelectorAll(".element").forEach(el => {
                el.classList.remove("active");
            });

            card.classList.add("active");
            showInfo(element);
        });

        table.appendChild(card);
    });
}

search.addEventListener("input", () => {
    const value = search.value.trim().toLowerCase();

    const filtered = elements.filter(element =>
        element.name.includes(value) ||
        element.symbol.toLowerCase().includes(value) ||
        String(element.number) === value ||
        element.family.includes(value) ||
        element.type.includes(value)
    );

    showElements(filtered);
});

showElements(elements);
